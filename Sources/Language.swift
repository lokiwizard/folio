func L(_ key: String) -> String {
    UIStrings.language == .english ? (UIStrings.english[key] ?? key) : key
}
func bilingual(_ chinese: String, _ english: String) -> String {
    UIStrings.language == .english ? english : chinese
}
func pageName(_ index: Int) -> String {
    bilingual("第 \(index + 1) 页", "Page \(index + 1)")
}

